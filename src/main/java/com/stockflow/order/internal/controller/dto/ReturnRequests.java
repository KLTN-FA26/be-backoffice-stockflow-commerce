package com.stockflow.order.internal.controller.dto;

import com.stockflow.order.internal.domain.ReturnReason;
import com.stockflow.order.internal.domain.ReturnResolution;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.util.List;
import java.util.UUID;

/**
 * Request bodies of the return endpoints (SCRUM-243 / SCRUM-260). A staff step may carry the {@code version} of the
 * return the screen showed: a return that moved meanwhile is refused with 409 {@code OPTIMISTIC_LOCK} rather than
 * decided on what the screen no longer shows.
 */
public final class ReturnRequests {

    private ReturnRequests() {
    }

    @Schema(description = "Units of one order line claimed")
    public record ClaimedLine(
            @NotNull(message = "orderLineId is required") UUID orderLineId,
            @Min(value = 1, message = "quantity must be at least 1") int quantity) {
    }

    @Schema(description = "Open a return on a delivered order (the customer on the portal, or Sales for them)")
    public record Open(
            @Schema(description = "Generated by the client once per form; sending it again returns the same return")
            @NotNull(message = "requestId is required") UUID requestId,
            @Schema(example = "PRINT_DEFECT") @NotNull(message = "reasonCode is required") ReturnReason reasonCode,
            @Schema(description = "What is wrong; required for OTHER")
            @Size(max = 2000, message = "description is at most 2000 characters") String description,
            @Schema(example = "REFUND", description = "Optional: REFUND, the only resolution since an exchange is a "
                    + "new quote")
            ReturnResolution requestedResolution,
            @NotEmpty(message = "claim at least one line") @Size(max = 100, message = "at most 100 lines")
            List<@Valid ClaimedLine> lines,
            @Schema(description = "Sales only: why a claim outside the return window is accepted (goods that came late, "
                    + "a defect found after the window, goodwill). Another person approves it")
            @Size(max = 500, message = "lateClaimReason is at most 500 characters") String lateClaimReason) {
    }

    @Schema(description = "Units approved of one return line (0: none of it)")
    public record ApprovedLine(
            @NotNull(message = "lineId is required") UUID lineId,
            @Min(value = 0, message = "approvedQuantity is not negative") int approvedQuantity) {
    }

    public record Approve(
            @Schema(description = "Lines left out are approved in full") @Size(max = 100) List<@Valid ApprovedLine> lines,
            @Schema(description = "Omitted or true: the goods always come back on a return receipt (17 BR-18); false "
                    + "is refused with RETURN_GOODS_REQUIRED")
            Boolean returnRequired,
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version) {
    }

    public record Reason(
            @NotBlank(message = "reason is required") @Size(max = 500, message = "reason is at most 500 characters")
            String reason,
            Long version) {
    }

    public record Cancel(@Size(max = 500, message = "reason is at most 500 characters") String reason) {
    }

    @Schema(description = "Units of one return line refunded")
    public record RefundLine(
            @NotNull(message = "lineId is required") UUID lineId,
            @Min(value = 0, message = "quantity is not negative") int quantity) {
    }

    @Schema(description = "The refund Sales propose for a RECEIVED return; no lines: every unit approved and back")
    public record Refund(
            @Size(max = 100) List<@Valid RefundLine> lines,
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version) {
    }

    public record Version(Long version) {
    }
}
