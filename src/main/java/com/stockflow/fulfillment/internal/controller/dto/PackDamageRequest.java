package com.stockflow.fulfillment.internal.controller.dto;

import com.stockflow.inventory.consumption.StockDamageReason;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;

import java.util.UUID;

/**
 * The {@code report} part of a damage report at packing (multipart, next to the {@code photos} parts), for units a
 * pick line already brought to the bench. The idempotency key travels in the body: the platform's idempotency filter
 * does not buffer uploads.
 */
@Schema(name = "PackDamageRequest", description = "Units of a picked line found damaged at the packing bench")
public record PackDamageRequest(

        @Schema(description = "Generated by the client once per report; the same value on a retry")
        @NotNull(message = "requestId is required")
        UUID requestId,

        @Schema(description = "1 to the units the line brought to packing, less any reported damaged already",
                example = "2")
        @NotNull(message = "damagedQuantity is required")
        @Positive(message = "damagedQuantity must be at least 1")
        Integer damagedQuantity,

        @Schema(description = "BROKEN, DEFORMED, WET_OR_MOULDY, DIRTY_OR_MISPRINTED or OTHER (then a note)")
        @NotNull(message = "reason is required")
        StockDamageReason reason,

        @Size(max = 1000, message = "note is at most 1000 characters")
        String note,

        @Schema(description = "The quarantine area the units are taken to; empty lets the system choose")
        @Size(max = 64, message = "damageLocationCode is at most 64 characters")
        String damageLocationCode
) {
}
