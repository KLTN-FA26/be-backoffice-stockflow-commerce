package com.stockflow.inventory.internal.controller.dto;

import com.stockflow.inventory.internal.domain.DamageReason;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;

import java.util.UUID;

/**
 * The {@code report} part of a damage report (multipart, next to the {@code photos} parts): which stock row, how many
 * units, why. The idempotency key travels in the body because the platform's idempotency filter does not buffer
 * uploads: a retried report with the same {@code requestId} answers with the first one.
 */
@Schema(name = "ReportDamageRequest", description = "Units of one stock row found damaged (BR-STK-003)")
public record ReportDamageRequest(

        @Schema(description = "Generated by the client once per report; the same value on a retry")
        @NotNull(message = "requestId is required")
        UUID requestId,

        @Schema(description = "The stock row, as the warehouse stock list shows it")
        @NotNull(message = "stockItemId is required")
        UUID stockItemId,

        @Schema(example = "3")
        @NotNull(message = "quantity is required")
        @Positive(message = "quantity must be at least 1")
        @Max(value = 1_000_000, message = "quantity is at most 1,000,000")
        Integer quantity,

        @Schema(description = "BROKEN, DEFORMED, WET_OR_MOULDY, DIRTY_OR_MISPRINTED or OTHER (then a note)")
        @NotNull(message = "reason is required")
        DamageReason reason,

        @Size(max = 1000, message = "note is at most 1000 characters")
        String note,

        @Schema(description = "The QUARANTINE area the goods are taken to; empty lets the system choose one",
                example = "HCM-QC01")
        @Size(max = 64, message = "damageLocationCode is at most 64 characters")
        String damageLocationCode
) {
}
