package com.stockflow.fulfillment.internal.controller.dto;

import com.stockflow.inventory.consumption.StockDamageReason;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;

import java.util.UUID;

/**
 * The {@code report} part of a damage report at picking (multipart, next to the {@code photos} parts). The
 * idempotency key travels in the body: the platform's idempotency filter does not buffer uploads.
 */
@Schema(name = "PickDamageRequest", description = "Units of a pick line found damaged at its bin (SCRUM-277)")
public record PickDamageRequest(

        @Schema(description = "Generated by the client once per report; the same value on a retry")
        @NotNull(message = "requestId is required")
        UUID requestId,

        @Schema(description = "The bin, as scanned", example = "HCM-A01-1-A")
        @NotBlank(message = "locationCode is required")
        @Size(max = 64, message = "locationCode is at most 64 characters")
        String locationCode,

        @Schema(description = "1 to the line's allocated quantity", example = "2")
        @NotNull(message = "damagedQuantity is required")
        @Positive(message = "damagedQuantity must be at least 1")
        Integer damagedQuantity,

        @Schema(description = "BROKEN, DEFORMED, WET_OR_MOULDY, DIRTY_OR_MISPRINTED or OTHER (then a note)")
        @NotNull(message = "reason is required")
        StockDamageReason reason,

        @Size(max = 1000, message = "note is at most 1000 characters")
        String note,

        @Schema(description = "The quarantine area the picker takes the units to; empty lets the system choose")
        @Size(max = 64, message = "damageLocationCode is at most 64 characters")
        String damageLocationCode
) {
}
