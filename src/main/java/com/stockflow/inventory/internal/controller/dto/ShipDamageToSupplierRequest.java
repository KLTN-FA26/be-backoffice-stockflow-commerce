package com.stockflow.inventory.internal.controller.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.util.UUID;

/** Units of a return-to-supplier decision handed to the supplier under a delivery note: some, or all it has left. */
@Schema(name = "ShipDamageToSupplierRequest")
public record ShipDamageToSupplierRequest(

        @Schema(description = "Generated by the client once per hand-over; the same value on a retry")
        @NotNull(message = "requestId is required")
        UUID requestId,

        @Schema(description = "Units handed over now; empty for all the decision has left", example = "8")
        @jakarta.validation.constraints.Positive(message = "quantity must be at least 1")
        Integer quantity,

        @Schema(description = "The number of the return delivery note the supplier or their carrier signed",
                example = "PXT-NCC-20261025-01")
        @NotBlank(message = "deliveryNote is required")
        @Size(max = 64, message = "deliveryNote is at most 64 characters")
        String deliveryNote,

        @Size(max = 1000, message = "note is at most 1000 characters")
        String note
) {
}
