package com.stockflow.identity.internal.controller;

import com.stockflow.identity.api.CreatedStaffUser;
import com.stockflow.identity.api.PasswordReset;
import com.stockflow.identity.api.StaffUser;
import com.stockflow.identity.api.UserStatusChangeEntry;
import com.stockflow.identity.internal.controller.dto.CreatedUserResponse;
import com.stockflow.identity.internal.controller.dto.PasswordResetResponse;
import com.stockflow.identity.internal.controller.dto.UserResponse;
import com.stockflow.identity.internal.controller.dto.UserStatusChangeResponse;
import com.stockflow.warehouse.api.WarehouseView;
import org.mapstruct.Context;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.ReportingPolicy;

import java.util.List;
import java.util.Map;
import java.util.UUID;

/** DTO mapping for user management, generated by MapStruct (pattern: {@code IdentityWebMapper}). */
@Mapper(componentModel = "spring", unmappedTargetPolicy = ReportingPolicy.ERROR)
interface UserManagementWebMapper {

    /**
     * @param warehouses the user's warehouses by id, looked up by the caller once for the whole page; an id it lacks
     *                   still appears, with no code or name
     */
    @Mapping(target = "warehouses", expression = "java(warehousesOf(user.warehouseIds(), warehouses))")
    UserResponse toResponse(StaffUser user, @Context Map<UUID, WarehouseView> warehouses);

    UserStatusChangeResponse toResponse(UserStatusChangeEntry entry);

    CreatedUserResponse toResponse(CreatedStaffUser created, @Context Map<UUID, WarehouseView> warehouses);

    PasswordResetResponse toResponse(PasswordReset reset);

    default List<UserResponse.Warehouse> warehousesOf(List<UUID> warehouseIds, Map<UUID, WarehouseView> found) {
        if (warehouseIds == null) {
            return List.of();
        }
        return warehouseIds.stream().map(id -> {
            WarehouseView warehouse = found.get(id);
            return new UserResponse.Warehouse(id, warehouse == null ? null : warehouse.prefix(),
                    warehouse == null ? null : warehouse.name());
        }).toList();
    }
}
