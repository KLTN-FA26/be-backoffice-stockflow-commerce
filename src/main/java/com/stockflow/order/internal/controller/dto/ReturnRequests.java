package com.stockflow.order.internal.controller.dto;

import com.stockflow.order.internal.domain.ReturnItemCondition;
import com.stockflow.order.internal.domain.ReturnReason;
import com.stockflow.order.internal.domain.ReturnResolution;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.util.List;
import java.util.UUID;

/**
 * Request bodies of the return endpoints (SCRUM-243 / SCRUM-260). A staff step may carry the {@code version} of the
 * return the screen showed: a return that moved meanwhile is refused with 409 {@code OPTIMISTIC_LOCK} rather than
 * decided on what the screen no longer shows.
 */
public final class ReturnRequests {

    private ReturnRequests() {
    }

    @Schema(description = "Units of one order line claimed")
    public record ClaimedLine(
            @NotNull(message = "orderLineId is required") UUID orderLineId,
            @Min(value = 1, message = "quantity must be at least 1") int quantity) {
    }

    @Schema(description = "Open a return on a delivered order (the customer on the portal, or Sales for them)")
    public record Open(
            @Schema(description = "Generated by the client once per form; sending it again returns the same return")
            @NotNull(message = "requestId is required") UUID requestId,
            @Schema(example = "PRINT_DEFECT") @NotNull(message = "reasonCode is required") ReturnReason reasonCode,
            @Schema(description = "What is wrong; required for OTHER")
            @Size(max = 2000, message = "description is at most 2000 characters") String description,
            @Schema(example = "REPLACEMENT") @NotNull(message = "requestedResolution is required")
            ReturnResolution requestedResolution,
            @NotEmpty(message = "claim at least one line") @Size(max = 100, message = "at most 100 lines")
            List<@Valid ClaimedLine> lines,
            @Schema(description = "Sales only: why a claim outside the return window is accepted (goods that came late, "
                    + "a defect found after the window, goodwill). Another person approves it")
            @Size(max = 500, message = "lateClaimReason is at most 500 characters") String lateClaimReason) {
    }

    @Schema(description = "Units approved of one return line (0: none of it)")
    public record ApprovedLine(
            @NotNull(message = "lineId is required") UUID lineId,
            @Min(value = 0, message = "approvedQuantity is not negative") int approvedQuantity) {
    }

    public record Approve(
            @Schema(description = "Lines left out are approved in full") @Size(max = 100) List<@Valid ApprovedLine> lines,
            @Schema(description = "Whether the goods come back; omitted: yes, unless it is a short delivery. False only "
                    + "up to the no-return value (stockflow.order.returns.no-return-max-value)")
            Boolean returnRequired,
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version) {
    }

    public record Reason(
            @NotBlank(message = "reason is required") @Size(max = 500, message = "reason is at most 500 characters")
            String reason,
            Long version) {
    }

    public record Cancel(@Size(max = 500, message = "reason is at most 500 characters") String reason) {
    }

    @Schema(description = "What arrived for one return line")
    public record ReceivedLine(
            @NotNull(message = "lineId is required") UUID lineId,
            @Min(value = 0, message = "quantity is not negative") int quantity,
            @Schema(description = "The SKU that arrived when it is not the line's (a wrong item)")
            @Size(max = 64) String sku,
            @Size(max = 64) String lotNumber) {
    }

    @Schema(description = "Something in the parcel that belongs to no line")
    public record UnexpectedItem(
            @Size(max = 64) String sku,
            @Min(value = 1, message = "quantity must be at least 1") int quantity,
            @Size(max = 500) String note) {
    }

    public record Receive(
            @Schema(description = "A quarantine or QC area; omitted: the order's warehouse's")
            @Size(max = 64) String locationCode,
            @NotEmpty(message = "count at least one line") @Size(max = 100) List<@Valid ReceivedLine> lines,
            @Size(max = 50) List<@Valid UnexpectedItem> unexpected,
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version) {
    }

    @Schema(description = "QC's verdict on one return line: of the units received, accepted (the claim holds) and "
            + "rejected; and where they go. Accepted units: back on sale (plain stock only, at a bin of the warehouse) "
            + "or scrap. Rejected units are the customer's: back to them, or scrap only with disposalConsent")
    public record InspectedLine(
            @NotNull(message = "lineId is required") UUID lineId,
            @Min(0) int acceptedQuantity,
            @Min(0) int rejectedQuantity,
            ReturnItemCondition condition,
            @Min(0) int restockQuantity,
            @Min(0) int scrapQuantity,
            @Min(0) int customerReturnQuantity,
            @Schema(description = "The bin units back on sale go to") @Size(max = 64) String restockLocationCode,
            @Size(max = 1000) String note,
            @Schema(description = "QC saw the units going back on sale are plain stock, no customer print. Omitted: "
                    + "true for the line's own SKU on a line that was not printed; another SKU must say so")
            Boolean plainStock,
            @Schema(description = "How the customer agreed that rejected units are scrapped instead of sent back")
            @Size(max = 500) String disposalConsent) {
    }

    public record Inspect(
            @NotEmpty(message = "inspect at least one line") @Size(max = 100) List<@Valid InspectedLine> lines,
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version) {
    }

    @Schema(description = "How one line's accepted units are made good")
    public record RemedyLine(
            @NotNull(message = "lineId is required") UUID lineId,
            @Min(0) int replacementQuantity,
            @Min(0) int creditQuantity) {
    }

    public record Resolve(
            @NotEmpty(message = "resolve at least one line") @Size(max = 100) List<@Valid RemedyLine> lines,
            @Schema(description = "REFUND or CREDIT_NOTE; required when any unit is credited")
            ReturnResolution moneyMode,
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version) {
    }

    public record Version(Long version) {
    }

    @Schema(description = "Withdraw a resolved return's replacement order before it ships; its units are credited")
    public record WithdrawReplacement(
            @NotBlank(message = "reason is required") @Size(max = 500, message = "reason is at most 500 characters")
            String reason,
            Long version) {
    }
}
