package com.stockflow.inventory.internal.controller.dto;

import com.stockflow.inventory.internal.domain.DamageDisposition;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;

import java.util.UUID;

@Schema(name = "DisposeDamageRequest",
        description = "A warehouse manager's decision on some units of a damage report; never the reporter's")
public record DisposeDamageRequest(

        @Schema(description = "Generated by the client once per decision; the same value on a retry")
        @NotNull(message = "requestId is required")
        UUID requestId,

        @Schema(description = "WRITE_OFF, RETURN_TO_SUPPLIER or RESTORE")
        @NotNull(message = "disposition is required")
        DamageDisposition disposition,

        @NotNull(message = "quantity is required")
        @Positive(message = "quantity must be at least 1")
        @Max(value = 1_000_000, message = "quantity is at most 1,000,000")
        Integer quantity,

        @Schema(description = "Required for RETURN_TO_SUPPLIER and RESTORE: why")
        @Size(max = 1000, message = "note is at most 1000 characters")
        String note,

        @Schema(description = "RESTORE only: the active bin of the same warehouse the goods go back onto",
                example = "HCM-A01-1-A")
        @Size(max = 64, message = "restoreLocationCode is at most 64 characters")
        String restoreLocationCode
) {
}
