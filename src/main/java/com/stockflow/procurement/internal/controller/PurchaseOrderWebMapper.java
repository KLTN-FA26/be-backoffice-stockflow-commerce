import com.stockflow.procurement.internal.controller.dto.UpdatePurchaseOrderRequest;

import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.ReportingPolicy;

import java.util.List;

/**
 * DTO mapping, generated by MapStruct at compile time. See {@code InventoryWebMapper} for why this
 * is used here and not in the persistence layer, and why {@code unmappedTargetPolicy = ERROR}.
 */
@Mapper(componentModel = "spring", unmappedTargetPolicy = ReportingPolicy.ERROR)
interface PurchaseOrderWebMapper {

    CreatePurchaseOrderCommand toCommand(CreatePurchaseOrderRequest request);

    CreatePOLineCommand toCommand(CreatePOLineRequest request);

    RevisePurchaseOrderCommand toCommand(UpdatePurchaseOrderRequest request);

    RevisePOLineCommand toCommand(UpdatePOLineRequest request);


    @Mapping(target = "revisionNo", source = "summary.revisionNo")
    @Mapping(target = "deliveryStatus", source = "deliveryStatus")
    PurchaseOrderResponse toResponse(
            PurchaseOrderSummary summary,
            String deliveryStatus,
            String cancellationDeliveryStatus,
            String amendmentDeliveryStatus,
            PendingAmendmentResponse pendingAmendment,
            List<String> warnings);

    @Mapping(target = "openQuantity", expression = "java(summary.openQuantity())")
    @Mapping(target = "openUnitQuantity", expression = "java(summary.openUnitQuantity())")
    @Mapping(target = "packingUnitPrice", expression = "java(summary.packingUnitPrice())")
    POLineResponse toResponse(POLineSummary summary);

    PurchaseOrderStatusCountResponse toResponse(PurchaseOrderStatusCount count);

    SupplierSpendResponse toResponse(SupplierSpendSummary summary);
}
