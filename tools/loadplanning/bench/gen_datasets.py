"""Write the benchmark datasets of SCRUM-474 part 3 (src/test/resources/loadplanning/bench/*.json).

    python3 -I gen_datasets.py OUT_DIR

Fixed seeds, so the files can be regenerated byte for byte. Sizes are in whole millimetres, drawn the way
LoadPlannerBenchmarkTest.realistic() draws them (250-1500 x 200-1100 x 150-1000 mm, weights 1-45 kg, about 80 % of the
cartons turnable); length runs along the vehicle, width across it.

  mixed800      800 cartons, every one a size of its own (the case in the ticket)
  realistic800  800 cartons over 200 sizes (a size per SKU; the template-like mix of repeated items), no sets
  mixed800_2..4 the same, three more draws (not committed: run with -Dloadplanning.datadir=OUT_DIR; the original needs
                about 15 minutes for one of these)
  mixed300_1..4 300 cartons, every one a size of its own, four seeds: the original takes about 5 minutes on one, so the
                two solvers can be compared over several draws (one draw of a randomised search proves little)
"""
import json, os, random, sys

def mixed(n, seed, prefix='m'):
    r = random.Random(seed)
    out = []
    for i in range(n):
        out.append(dict(ref='%s%d' % (prefix, i), part='%s%d' % (prefix.upper(), i), l=250 + r.randint(0, 1250), w=200 + r.randint(0, 900),
                        h=150 + r.randint(0, 850), kg=round(1 + r.random() * 44, 3), rot=r.random() < 0.8))
    return out

def mixed800():
    return mixed(800, 474)

def realistic800():
    r = random.Random(475)
    skus = [(250 + r.randint(0, 1250), 200 + r.randint(0, 900), 150 + r.randint(0, 850)) for _ in range(200)]
    out = []
    for i in range(800):
        s = r.randrange(200)
        l, w, h = skus[s]
        out.append(dict(ref='r%d' % i, part='SKU%d' % s, l=l, w=w, h=h, kg=round(1 + r.random() * 44, 3),
                        rot=r.random() < 0.8))
    return out

if __name__ == '__main__':
    d = sys.argv[1]
    os.makedirs(d, exist_ok=True)
    sets = [('mixed800', mixed800), ('realistic800', realistic800)]
    sets += [('mixed800_%d' % k, (lambda k=k: mixed(800, 4740 + k))) for k in range(2, 5)]
    sets += [('mixed300_%d' % k, (lambda k=k: mixed(300, 3000 + k))) for k in range(1, 5)]
    for name, fn in sets:
        json.dump(dict(name=name, cartons=fn()), open(os.path.join(d, name + '.json'), 'w'), separators=(',', ':'))
        print(name)
