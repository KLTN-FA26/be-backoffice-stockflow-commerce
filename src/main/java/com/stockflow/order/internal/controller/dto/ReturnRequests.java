package com.stockflow.order.internal.controller.dto;

import com.stockflow.order.internal.domain.ReturnReason;
import com.stockflow.order.internal.domain.ReturnRefusalReason;
import com.stockflow.order.internal.domain.ReturnResolution;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.util.List;
import java.util.UUID;

/**
 * Request bodies of the return endpoints (SCRUM-243 / SCRUM-260). A staff step may carry the {@code version} of the
 * return the screen showed: a return that moved meanwhile is refused with 409 {@code OPTIMISTIC_LOCK} rather than
 * decided on what the screen no longer shows.
 */
public final class ReturnRequests {

    private ReturnRequests() {
    }

    @Schema(description = "Units of one order line claimed")
    public record ClaimedLine(
            @NotNull(message = "orderLineId is required") UUID orderLineId,
            @Min(value = 1, message = "quantity must be at least 1") int quantity) {
    }

    @Schema(description = "Open a return on a delivered order (the customer on the portal, or Sales for them)")
    public record Open(
            @Schema(description = "Generated by the client once per form; sending it again returns the same return")
            @NotNull(message = "requestId is required") UUID requestId,
            @Schema(example = "PRINT_DEFECT") @NotNull(message = "reasonCode is required") ReturnReason reasonCode,
            @Schema(description = "What is wrong; required for OTHER")
            @Size(max = 2000, message = "description is at most 2000 characters") String description,
            @Schema(example = "REFUND", description = "Optional: REFUND, the only resolution since an exchange is a "
                    + "new quote")
            ReturnResolution requestedResolution,
            @NotEmpty(message = "claim at least one line") @Size(max = 100, message = "at most 100 lines")
            List<@Valid ClaimedLine> lines,
            @Schema(description = "Sales only: why a claim outside the return window is accepted (goods that came late, "
                    + "a defect found after the window, goodwill). Another person approves it")
            @Size(max = 500, message = "lateClaimReason is at most 500 characters") String lateClaimReason,
            @Schema(description = "The delivered shipment the goods came on (WF-05 TH-1: one return per delivery). "
                    + "Omitted: the order's only delivered shipment; required (RETURN_SHIPMENT_REQUIRED) once the order "
                    + "was delivered in several. A shipment not delivered: RETURN_SHIPMENT_NOT_DELIVERED. The customer "
                    + "reads it from GET /api/v1/orders/me/{orderId} as shipments[].shipmentId (CustomerOrderShipment); "
                    + "back-office from the order's shipments")
            UUID shipmentId) {
    }

    @Schema(description = "Units approved of one return line (0: none of it)")
    public record ApprovedLine(
            @NotNull(message = "lineId is required") UUID lineId,
            @Min(value = 0, message = "approvedQuantity is not negative") int approvedQuantity) {
    }

    public record Approve(
            @Schema(description = "Lines left out are approved in full") @Size(max = 100) List<@Valid ApprovedLine> lines,
            @Schema(description = "Omitted or true: the goods always come back on a return receipt (17 BR-18); false "
                    + "is refused with RETURN_GOODS_REQUIRED")
            Boolean returnRequired,
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version) {
    }

    public record Reason(
            @NotBlank(message = "reason is required") @Size(max = 500, message = "reason is at most 500 characters")
            String reason,
            Long version) {
    }

    public record Cancel(@Size(max = 500, message = "reason is at most 500 characters") String reason) {
    }

    @Schema(description = "Units of one return line refunded")
    public record RefundLine(
            @NotNull(message = "lineId is required") UUID lineId,
            @Min(value = 0, message = "quantity is not negative") int quantity) {
    }

    @Schema(description = "The refund Sales propose for a RECEIVED return; no lines: every unit approved and back. "
            + "Every line at 0 while units came back usable is a refusal (WF-05 Q-4): refusalReason is then required "
            + "(400 RETURN_REFUSAL_REASON_REQUIRED), and the accountant approves it like any refund")
    public record Refund(
            @Size(max = 100) List<@Valid RefundLine> lines,
            @Schema(description = "Internal: never shown to the customer")
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version,
            @Schema(description = "Why units that came back are not refunded: required when none is, refused when all "
                    + "are; the customer sees its label", example = "CUSTOMER_DAMAGE",
                    allowableValues = {"CUSTOMER_DAMAGE", "NOT_DEFECTIVE", "OUT_OF_POLICY", "OTHER"})
            ReturnRefusalReason refusalReason,
            @Schema(description = "The note the customer reads beside the reason; required for OTHER")
            @Size(max = 500, message = "refusalNote is at most 500 characters") String refusalNote) {

        /** Nothing withheld for a reason. */
        public Refund(List<RefundLine> lines, String note, Long version) {
            this(lines, note, version, null, null);
        }
    }

    public record Version(Long version) {
    }

    @Schema(description = "A custody note (WF-05 Q-11): goods that came back and that the return does not take - another "
            + "SKU, more than approved, a parcel after the claim was settled or refused - kept for the customer, not in "
            + "stock, not refunded. A photo uploaded through /custody/uploads, the SKU or the LPN, and how many")
    public record Custody(
            @NotNull(message = "uploadId is required") UUID uploadId,
            @Size(max = 64, message = "sku is at most 64 characters") String sku,
            @Size(max = 40, message = "lpn is at most 40 characters") String lpn,
            @Min(value = 1, message = "quantity must be at least 1") int quantity,
            @Size(max = 1000, message = "note is at most 1000 characters") String note) {
    }

    @Schema(description = "What the customer chose for the cartons of a return held for them - those its refund did not "
            + "take back (WF-05 Q-4): SEND_BACK (at their cost) or DESTROY_ON_BEHALF (note names their written consent)")
    public record CustodyChoice(
            @NotNull(message = "choice is required") com.stockflow.order.internal.domain.ReturnCustodyChoice choice,
            @Size(max = 500, message = "note is at most 500 characters") String note,
            Long version) {
    }

    @Schema(description = "What the customer chose for the goods of a custody note (WF-05 Q-11; audit r3 RAD-3): "
            + "SEND_BACK (at their cost), DESTROY_ON_BEHALF (note names their written consent) or TAKEN_BY_RETURN "
            + "(takenByReturnId: the supplementary return of the same customer that takes them)")
    public record CustodyNoteChoice(
            @NotNull(message = "choice is required")
            com.stockflow.order.internal.domain.ReturnCustodyNoteChoice choice,
            @Size(max = 500, message = "note is at most 500 characters") String note,
            UUID takenByReturnId) {
    }

    @Schema(description = "The goods of a custody note left as the customer chose: note is the record of it (hand-over "
            + "note, destruction record, the receipt of the supplementary return)")
    public record EndCustodyNote(
            @NotBlank(message = "note is required")
            @Size(max = 500, message = "note is at most 500 characters") String note) {
    }

    @Schema(description = "The goods of an AWAITING_RETURN return are all here, fewer than approved (WF-05 TH-3)")
    public record GoodsComplete(
            @Size(max = 500, message = "note is at most 500 characters") String note,
            Long version) {
    }

    @Schema(description = "Close a RECEIVED return with no refund: nothing approved came back usable (WF-05 TH-4)")
    public record CloseWithoutRefund(
            @Size(max = 1000, message = "note is at most 1000 characters") String note,
            Long version) {
    }
}
