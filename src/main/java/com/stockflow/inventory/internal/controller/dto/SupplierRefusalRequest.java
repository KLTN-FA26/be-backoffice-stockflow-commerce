package com.stockflow.inventory.internal.controller.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;

import java.util.UUID;

/** Units of a return-to-supplier decision the supplier refused, or did not take: they wait for a decision again. */
@Schema(name = "SupplierRefusalRequest")
public record SupplierRefusalRequest(

        @Schema(description = "Generated by the client once per refusal; the same value on a retry")
        @NotNull(message = "requestId is required")
        UUID requestId,

        @Schema(example = "2")
        @NotNull(message = "quantity is required")
        @Positive(message = "quantity must be at least 1")
        Integer quantity,

        @Schema(description = "What the supplier answered")
        @NotBlank(message = "note is required")
        @Size(max = 1000, message = "note is at most 1000 characters")
        String note
) {
}
